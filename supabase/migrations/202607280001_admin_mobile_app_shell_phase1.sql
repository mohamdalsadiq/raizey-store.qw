CREATE OR REPLACE FUNCTION public.set_row_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := timezone('utc', now());
  RETURN NEW;
END;
$$;

-- -----------------------------------------------------------------------------
-- الجداول الأساسية للمرحلة الأولى
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.store_settings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  singleton_key boolean NOT NULL DEFAULT true,
  maintenance_mode boolean NOT NULL DEFAULT false,
  maintenance_message text NOT NULL DEFAULT 'الموقع قيد الصيانة والتحديث حالياً، وسنسعد بخدمتكم مجدداً في أقرب وقت ممكن.',
  usd_to_sdg_rate numeric(12, 2) NOT NULL DEFAULT 0 CHECK (usd_to_sdg_rate >= 0),
  updated_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT store_settings_singleton_key_uniq UNIQUE (singleton_key),
  CONSTRAINT store_settings_singleton_key_check CHECK (singleton_key = true)
);

CREATE TABLE IF NOT EXISTS public.admin_permissions (
  profile_id uuid PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
  is_super_admin boolean NOT NULL DEFAULT false,
  can_manage_orders boolean NOT NULL DEFAULT false,
  can_manage_wallets boolean NOT NULL DEFAULT false,
  can_manage_products boolean NOT NULL DEFAULT false,
  can_manage_settings boolean NOT NULL DEFAULT false,
  can_manage_maintenance boolean NOT NULL DEFAULT false,
  can_manage_admins boolean NOT NULL DEFAULT false,
  can_manage_coupons boolean NOT NULL DEFAULT false,
  can_manage_gift_cards boolean NOT NULL DEFAULT false,
  can_view_audit_logs boolean NOT NULL DEFAULT false,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  admin_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  action text NOT NULL,
  target_table text,
  target_id text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE INDEX IF NOT EXISTS idx_admin_permissions_super_admin
  ON public.admin_permissions (is_super_admin)
  WHERE is_super_admin = true;

CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_admin_id_created_at
  ON public.admin_audit_logs (admin_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_target
  ON public.admin_audit_logs (target_table, target_id);

DROP TRIGGER IF EXISTS trg_store_settings_set_updated_at ON public.store_settings;
CREATE TRIGGER trg_store_settings_set_updated_at
BEFORE UPDATE ON public.store_settings
FOR EACH ROW
EXECUTE FUNCTION public.set_row_updated_at();

DROP TRIGGER IF EXISTS trg_admin_permissions_set_updated_at ON public.admin_permissions;
CREATE TRIGGER trg_admin_permissions_set_updated_at
BEFORE UPDATE ON public.admin_permissions
FOR EACH ROW
EXECUTE FUNCTION public.set_row_updated_at();

-- -----------------------------------------------------------------------------
-- Seed أولي متوافق مع الإعدادات القديمة
-- -----------------------------------------------------------------------------
DO $$
DECLARE
  v_initial_rate numeric := 0;
BEGIN
  IF to_regclass('public.settings') IS NOT NULL THEN
    SELECT COALESCE(
      (
        SELECT CASE
          WHEN value ~ '^[0-9]+(\.[0-9]+)?$' THEN value::numeric
          ELSE 0
        END
        FROM public.settings
        WHERE key = 'usd_to_sdg_rate'
        LIMIT 1
      ),
      0
    )
    INTO v_initial_rate;
  END IF;

  INSERT INTO public.store_settings (
    singleton_key,
    maintenance_mode,
    maintenance_message,
    usd_to_sdg_rate
  )
  SELECT
    true,
    false,
    'الموقع قيد الصيانة والتحديث حالياً، وسنسعد بخدمتكم مجدداً في أقرب وقت ممكن.',
    v_initial_rate
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.store_settings
  );
END;
$$;

