ALTER TABLE public.store_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_audit_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "store_settings_public_read" ON public.store_settings;
CREATE POLICY "store_settings_public_read"
ON public.store_settings
FOR SELECT
USING (true);

DROP POLICY IF EXISTS "admin_permissions_self_read" ON public.admin_permissions;
CREATE POLICY "admin_permissions_self_read"
ON public.admin_permissions
FOR SELECT
USING (profile_id = auth.uid());

DROP POLICY IF EXISTS "admin_permissions_super_admin_read" ON public.admin_permissions;
CREATE POLICY "admin_permissions_super_admin_read"
ON public.admin_permissions
FOR SELECT
USING (public.is_super_admin());

DROP POLICY IF EXISTS "admin_audit_logs_self_or_privileged_read" ON public.admin_audit_logs;
CREATE POLICY "admin_audit_logs_self_or_privileged_read"
ON public.admin_audit_logs
FOR SELECT
USING (
  admin_id = auth.uid()
  OR public.is_super_admin()
  OR public.has_admin_permission('view_audit_logs')
);

REVOKE ALL ON public.store_settings FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.admin_permissions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.admin_audit_logs FROM PUBLIC, anon, authenticated;

GRANT SELECT ON public.store_settings TO anon, authenticated;
GRANT SELECT ON public.admin_permissions TO authenticated;
GRANT SELECT ON public.admin_audit_logs TO authenticated;

GRANT EXECUTE ON FUNCTION public.is_admin() TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.is_super_admin() TO authenticated;
GRANT EXECUTE ON FUNCTION public.has_admin_permission(text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_my_admin_context() TO authenticated;
GRANT EXECUTE ON FUNCTION public.append_admin_audit_log(text, text, text, jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.set_store_exchange_rate(numeric) TO authenticated;
GRANT EXECUTE ON FUNCTION public.set_store_maintenance(boolean, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.upsert_admin_permissions(
  uuid,
  boolean,
  boolean,
  boolean,
  boolean,
  boolean,
  boolean,
  boolean,
  boolean,
  boolean,
  boolean
) TO authenticated;
GRANT EXECUTE ON FUNCTION public.bootstrap_super_admin() TO authenticated;

