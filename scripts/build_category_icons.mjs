// Build only our selected Phosphor Duotone artwork; no remote runtime requests.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
const require = createRequire(import.meta.url);
const { PRESETS } = require('../assets/js/category-icons.js');
const mapping = JSON.parse(fs.readFileSync('assets/icons/category-phosphor-map.json', 'utf8'));
const packageDir = 'node_modules/@phosphor-icons/core';
const { version } = JSON.parse(fs.readFileSync(`${packageDir}/package.json`, 'utf8'));
if (version !== '2.1.1') throw new Error('Unexpected Phosphor version');
const symbols = PRESETS.map(key => {
  const name = mapping[key];
  if (!name || !/^[a-z0-9-]+$/.test(name)) throw new Error(`Missing mapping: ${key}`);
  const source = fs.readFileSync(`${packageDir}/assets/duotone/${name}-duotone.svg`, 'utf8');
  if (/<(?:script|foreignObject)|\bon\w+=|href=/i.test(source)) throw new Error(`Unsafe SVG: ${name}`);
  const body = source.replace(/^<svg[^>]+>/, '').replace(/<\/svg>\s*$/, '');
  return `<symbol id="i-${key}" viewBox="0 0 256 256" fill="currentColor" stroke="none">${body}</symbol>`;
});
const sprite = `<!-- Phosphor Icons ${version}, MIT; generated by scripts/build_category_icons.mjs -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;
fs.writeFileSync('assets/icons/category-sprite.svg', sprite);
fs.copyFileSync(`${packageDir}/LICENSE`, 'assets/icons/PHOSPHOR-LICENSE.txt');
fs.writeFileSync('assets/icons/category-source.json', JSON.stringify({
  package: '@phosphor-icons/core', version, style: 'duotone',
  source: 'https://github.com/phosphor-icons/core', license: 'MIT',
  icons: PRESETS.length, sha256: createHash('sha256').update(sprite).digest('hex')
}, null, 2) + '\n');
console.log(`Built ${symbols.length} category icons (${Buffer.byteLength(sprite)} bytes).`);
