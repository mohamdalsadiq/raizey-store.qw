#!/usr/bin/env python3
"""Wire the MEEM STORE master artwork into every page.

Idempotent: re-running produces the same markup. Every placement uses the
assets generated by scripts/build_meem_assets.py (derived from the client's
PNGs in assets/source/ — nothing is drawn by hand).
"""
import os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

report = []


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    with open(p, "w", encoding="utf-8") as f:
        f.write(s)


def sub(path, pattern, repl, count=1, flags=0, label=""):
    s = read(path)
    new, n = re.subn(pattern, repl, s, count=count, flags=flags)
    if n:
        write(path, new)
        report.append("%s  %s" % (path, label or pattern[:50]))
    return n


MARK = ('<img class="brand-mark" src="assets/img/meem-mark-{h}.png"\n'
        '           srcset="assets/img/meem-mark-48.png 1x, assets/img/meem-mark-96.png 2x"\n'
        '           alt="MEEM STORE" width="44" height="44" decoding="async">')

HEADER_BRAND = (
    '    <a class="logo brand-lockup" href="index.html" aria-label="MEEM STORE">\n'
    '      <img class="brand-mark" src="assets/img/meem-mark-48.png"\n'
    '           srcset="assets/img/meem-mark-48.png 1x, assets/img/meem-mark-96.png 2x"\n'
    '           alt="MEEM STORE" width="44" height="44" fetchpriority="high" decoding="async">\n'
    '      <img class="brand-name" src="assets/img/meem-wordmark-28.png"\n'
    '           srcset="assets/img/meem-wordmark-28.png 1x, assets/img/meem-wordmark-56.png 2x"\n'
    '           alt="" aria-hidden="true" width="104" height="28" decoding="async">\n'
    '    </a>')

LOCKUP_IMG = ('<img class="brand-lockup" src="assets/img/meem-lockup-{h}.png"\n'
              '        srcset="assets/img/meem-lockup-200.png 1x, assets/img/meem-lockup-400.png 2x"\n'
              '        alt="MEEM STORE" width="304" height="200" decoding="async">')

FOOTER_BRAND = (
    '<div class="footer-brand">\n'
    '      <img class="footer-logo" src="assets/img/meem-lockup-200.png"\n'
    '           srcset="assets/img/meem-lockup-200.png 1x, assets/img/meem-lockup-400.png 2x"\n'
    '           alt="MEEM STORE" width="304" height="200" loading="lazy" decoding="async">\n'
    '      <p class="footer-copy"><img class="footer-mark" src="assets/img/meem-mark-48.png" alt="" aria-hidden="true"\n'
    '           width="20" height="20" loading="lazy" decoding="async"> © 2026 MEEM STORE — جميع الحقوق محفوظة</p>\n'
    '    </div>')

ADMIN_BRAND = (
    '  <div class="page-header">\n'
    '    <div class="admin-brand">\n'
    '      <img class="admin-brand-mark" src="assets/img/meem-mark-48.png"\n'
    '           srcset="assets/img/meem-mark-48.png 1x, assets/img/meem-mark-96.png 2x"\n'
    '           alt="MEEM STORE" width="36" height="36" decoding="async">\n'
    '      <img class="admin-brand-name" src="assets/img/meem-wordmark-28.png"\n'
    '           srcset="assets/img/meem-wordmark-28.png 1x, assets/img/meem-wordmark-56.png 2x"\n'
    '           alt="" aria-hidden="true" width="90" height="24" decoding="async">\n'
    '    </div>\n'
    '    <h1>{title}</h1>\n'
    '    <a href="index.html" class="back-link">→ المتجر</a>\n'
    '  </div>')

html_all = sorted(glob.glob("*.html"))

# ── 1. Header lockup (index.html + search.html) ───────────────────────────
idx = read("index.html")
new_idx = re.sub(r'<a class="logo[^"]*" href="index\.html" aria-label="MEEM STORE">.*?</a>',
                 HEADER_BRAND.strip(), idx, count=1, flags=re.S)
if new_idx != idx:
    write("index.html", new_idx)
    report.append("index.html  header: mark + MEEM STORE wordmark lockup")

s = read("search.html")
s2 = re.sub(r'<div class="logo"[^>]*>.*?</div>',
            '<a class="logo brand-lockup" href="index.html" aria-label="MEEM STORE">\n'
            + HEADER_BRAND.strip().replace('class="logo brand-lockup" href="index.html" aria-label="MEEM STORE">', '')[1:]
            + '\n    </a>',
            s, count=1, flags=re.S)
if s2 != s:
    write("search.html", s2)
    report.append("search.html  header: replaced commented text fallback with real lockup")

# ── 2. Auth / verify / privacy / receipt lockups ─────────────────────────
for p in ("login.html", "register.html", "forgot-password.html", "reset-password.html",
          "verify.html", "privacy.html"):
    sub(p, r'<img class="brand-lockup" src="assets/img/meem-logo\.png"[^>]*>',
        LOCKUP_IMG.format(h=200), label="auth card: MEEM STORE lockup")
sub("receipt.html", r'<img class="brand-lockup" src="assets/img/meem-logo\.png"[^>]*>',
    LOCKUP_IMG.format(h=200), label="receipt header: MEEM STORE lockup")

# ── 3. Footer brand (index.html + search.html) ───────────────────────────
for p in ("index.html", "search.html"):
    s = read(p)
    if "footer-brand" in s:
        continue
    new, n = re.subn(r'<footer class="site-footer"[^>]*>\s*<p>[^<]*</p>\s*</footer>',
                     '<footer class="site-footer">\n    ' + FOOTER_BRAND + '\n    </footer>',
                     s, count=1)
    if n:
        write(p, new)
        report.append("%s  footer: large MEEM STORE lockup + mark in copyright line" % p)

# ── 4. Admin console brand ───────────────────────────────────────────────
ADMIN_BRAND_INLINE = (
    '\n    <div class="admin-brand">\n'
    '      <img class="admin-brand-mark" src="assets/img/meem-mark-48.png"\n'
    '           srcset="assets/img/meem-mark-48.png 1x, assets/img/meem-mark-96.png 2x"\n'
    '           alt="MEEM STORE" width="36" height="36" decoding="async">\n'
    '      <img class="admin-brand-name" src="assets/img/meem-wordmark-28.png"\n'
    '           srcset="assets/img/meem-wordmark-28.png 1x, assets/img/meem-wordmark-56.png 2x"\n'
    '           alt="" aria-hidden="true" width="90" height="24" decoding="async">\n'
    '    </div>')

for p in sorted(glob.glob("admin*.html")):
    s = read(p)
    if "admin-brand" in s:
        continue
    m = re.search(r'<div class="page-header">(\s*)<h1>.*?</h1>\s*<a[^>]*class="back-link".*?</a>\s*</div>', s, re.S)
    if not m:
        continue
    write(p, s[:m.end() - len('</div>')] + ADMIN_BRAND_INLINE + '\n  </div>' + s[m.end():])
    report.append("%s  admin header: mark + MEEM STORE wordmark" % p)

# ── 5. Favicon set: add the 512 icon ─────────────────────────────────────
for p in html_all:
    s = read(p)
    if "favicon-512" in s or 'rel="apple-touch-icon"' not in s:
        continue
    new = s.replace('<link rel="apple-touch-icon"',
                    '<link rel="icon" type="image/png" sizes="512x512" href="assets/img/favicon-512.png">\n<link rel="apple-touch-icon"', 1)
    write(p, new)
    report.append("%s  favicon: 512px added" % p)

print("\n".join(report) if report else "no changes")
print("---- %d placements ----" % len(report))
